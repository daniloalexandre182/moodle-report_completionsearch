namespace report_completionsearch\local;

/**
 * Builds the SQL fragment that filters tracked users by full name, email or username.
 *
 * The generated fragment refers to the user table through the alias `u`, as expected by
 * {@see \completion_info::get_num_tracked_users()} and {@see \completion_info::get_progress_all()}.
 *
 * @package    report_completionsearch
 * @copyright  2026 Danilo Machado <danilo.alexandre182@gmail.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class user_filter {
    /** Search in the user full name (first name + last name). */
    public const FIELD_FULLNAME = 'fullname';

    /** Search in the user email address. */
    public const FIELD_EMAIL = 'email';

    /** Search in the user username. */
    public const FIELD_USERNAME = 'username';

    /** Prefix used for every named SQL parameter generated by this class. */
    protected const PARAM_PREFIX = 'rcsearch';

    /** @var string The field being searched, one of the FIELD_* constants. */
    protected $field;

    /** @var string The text being searched for, as provided. */
    protected $text;

    /**
     * Constructor.
     *
     * @param string $field One of the FIELD_* constants.
     * @param string $text The text to search for (an empty/blank text matches every user).
     * @throws \coding_exception on unknown field
     */
    public function __construct(string $field, string $text) {
        if (!in_array($field, self::get_all_fields(), true)) {
            throw new \coding_exception('Invalid search field: ' . $field);
        }
        $this->field = $field;
        $this->text = $text;
    }

    /**
     * Returns every field supported by the filter, regardless of capabilities.
     *
     * @return string[]
     */
    public static function get_all_fields(): array {
        return [self::FIELD_FULLNAME, self::FIELD_EMAIL, self::FIELD_USERNAME];
    }

    /**
     * Returns the fields the current user may search on, as key => label.
     *
     * Email and username are only offered to users allowed to see user identity data, so the search
     * cannot be abused as an oracle to discover hidden identity information.
     *
     * @param \context $context The context the report is being viewed in.
     * @return array field key => localised label
     */
    public static function get_field_options(\context $context): array {
        $options = [
            self::FIELD_FULLNAME => get_string('searchfield_fullname', 'report_completionsearch'),
        ];
        if (has_capability('moodle/site:viewuseridentity', $context)) {
            $options[self::FIELD_EMAIL] = get_string('searchfield_email', 'report_completionsearch');
            $options[self::FIELD_USERNAME] = get_string('searchfield_username', 'report_completionsearch');
        }
        return $options;
    }

    /**
     * Returns the searched field.
     *
     * @return string
     */
    public function get_field(): string {
        return $this->field;
    }

    /**
     * Returns the searched text, as provided to the constructor.
     *
     * @return string
     */
    public function get_text(): string {
        return $this->text;
    }

    /**
     * Whether the filter actually restricts the users (i.e. the search text is not blank).
     *
     * @return bool
     */
    public function is_active(): bool {
        return trim($this->text) !== '';
    }

    /**
     * Returns the SQL WHERE fragment and its parameters.
     *
     * The comparison is a case-insensitive and (as far as the database allows) accent-insensitive
     * "contains" LIKE.
     *
     * @return array [string $where, array $params]; ['', []] when the search text is blank.
     */
    public function get_sql(): array {
        global $DB;

        $text = trim($this->text);
        if ($text === '') {
            return ['', []];
        }

        switch ($this->field) {
            case self::FIELD_EMAIL:
                $column = 'u.email';
                break;
            case self::FIELD_USERNAME:
                $column = 'u.username';
                break;
            case self::FIELD_FULLNAME:
            default:
                $column = $DB->sql_fullname('u.firstname', 'u.lastname');
                break;
        }

        $paramname = self::PARAM_PREFIX . $this->field;
        $where = $DB->sql_like($column, ':' . $paramname, false, false);
        $params = [$paramname => '%' . $DB->sql_like_escape($text) . '%'];

        return [$where, $params];
    }
}
